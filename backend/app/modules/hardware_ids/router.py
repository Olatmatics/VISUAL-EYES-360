"""Admin-only Hardware ID Generator.

Creates a station, one dispenser and its nozzles in one step, with short
copyable codes instead of long database UUIDs. It also returns ready-to-paste
ESP32 configuration blocks so non-technical staff never edit IDs by hand.

The long UUIDs still exist internally; the short codes are accepted by the
device-facing endpoints through ``app.core.id_resolve``.
"""

import uuid
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.deps import require_super_admin, write_audit
from app.core.validation import utcnow
from app.db.base import get_db
from app.models.auth import User
from app.models.core import Dispenser, FCCDevice, Nozzle, POSTerminal, Station

router = APIRouter(prefix="/api/v1/hardware-ids", tags=["hardware-ids"])


def _code(db: Session, model, column, prefix: str) -> str:
    """Generate a short, unique, human-copyable code."""
    while True:
        candidate = f"{prefix}-{uuid.uuid4().hex[:6].upper()}"
        exists = db.scalar(select(model).where(func.upper(column) == candidate.upper()))
        if exists is None:
            return candidate


def _defs(pairs: list[tuple[str, str]]) -> str:
    width = max(len(name) for name, _ in pairs)
    return "\n".join(f"const char* {name.ljust(width)} = \"{value}\";" for name, value in pairs)


def _board01_block(station, dispenser, nozzles, fcc_uids, pos_ids, payload) -> str:
    first = nozzles[0] if nozzles else None
    second = nozzles[1] if len(nozzles) > 1 else None
    pairs = [
        ("DEF_WIFI_SSID", str(payload.get("wifi_ssid") or "cypher")),
        ("DEF_WIFI_PASS", str(payload.get("wifi_pass") or "12345678")),
        ("DEF_BACKEND", str(payload.get("backend_url") or "http://172.25.0.37:8000")),
        ("DEF_STATION", station.code),
        ("DEF_NOZZLE_A", first.code if first else ""),
        ("DEF_NOZZLE_B", second.code if second else ""),
        ("DEF_DEVICE_A", fcc_uids[0] if fcc_uids else ""),
        ("DEF_DEVICE_B", fcc_uids[1] if len(fcc_uids) > 1 else ""),
        ("DEF_POS", pos_ids[0] if pos_ids else ""),
        ("DEF_DISPENSER", dispenser.code),
    ]
    lines = [
        "// VISUAL EYES 360 — generated by Hardware ID Generator",
        "// Board 01 FCC controller. Paste over the DEF_* block near the top of",
        "// firmware/prototype/01_fcc_pump/fcc_pump/fcc_pump.ino, then upload.",
        "// On a board that already has saved settings, type FACTORY then REBOOT.",
        "",
        _defs(pairs),
        "",
        f"const char* FIRMWARE = \"ve360-fcc-bench-1.1\";",
        "",
        "// Or paste these in Serial Monitor instead of editing the sketch:",
    ]
    for name, value in pairs:
        if name in {"DEF_WIFI_SSID", "DEF_WIFI_PASS"}:
            continue
        key = name[4:]
        lines.append(f"// SET {key} {value}")
    lines.append(f"// SET WIFI {pairs[0][1]}|{pairs[1][1]}")
    lines.append(f"// SET PRICE {payload.get('price') or 1000}")
    lines.append(f"// SET PPL {payload.get('pulses_per_litre') or 100}")
    return "\n".join(lines)


