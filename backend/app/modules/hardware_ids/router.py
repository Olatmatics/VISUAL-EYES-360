@router.post("/generate")
def generate(
    payload: dict[str, Any],
    request: Request,
    db: Session = Depends(get_db),
    admin: User = Depends(require_super_admin),
):
    """Create a complete bench hardware set with short, copyable IDs."""
    name = str(payload.get("station_name") or "").strip()
    if len(name) < 2:
        raise HTTPException(400, "Station name is required")

    try:
        count = int(payload.get("nozzle_count") or 2)
    except (TypeError, ValueError):
        raise HTTPException(400, "nozzle_count must be a number")
    if not 1 <= count <= 12:
        raise HTTPException(400, "nozzle_count must be between 1 and 12")

    try:
        price = float(payload.get("price") or 1000)
    except (TypeError, ValueError):
        raise HTTPException(400, "price must be a number")
    if price <= 0:
        raise HTTPException(400, "price must be greater than zero")

    station_code = str(payload.get("station_code") or "").strip() or _code(db, Station, Station.code, "ST")
    if db.scalar(select(Station).where(func.upper(Station.code) == station_code.upper())):
        raise HTTPException(409, "Station code already exists")

    station = Station(
        id=str(uuid.uuid4()), code=station_code, name=name,
        country=str(payload.get("country") or "Nigeria"),
        state_id=payload.get("state_id"), lga_id=payload.get("lga_id"),
        city=payload.get("city"), address=payload.get("address"),
        gps_lat=payload.get("gps_lat"), gps_lng=payload.get("gps_lng"),
        manager_name=payload.get("manager_name"), manager_phone=payload.get("manager_phone"),
        supervisor_name=payload.get("supervisor_name"), supervisor_phone=payload.get("supervisor_phone"),
        status="ACTIVE", registered_at=utcnow(),
    )
    db.add(station)
    db.flush()

    dispenser_code = _code(db, Dispenser, Dispenser.code, "PMP")
    dispenser = Dispenser(
        id=str(uuid.uuid4()), station_id=station.id, code=dispenser_code,
        name=str(payload.get("dispenser_name") or f"Pump {dispenser_code}"),
        serial=f"DSP-{uuid.uuid4().hex[:8].upper()}",
        manufacturer="Wayne", model="Prototype",
        nozzle_config="SINGLE" if count == 1 else ("DOUBLE" if count == 2 else "OTHER"),
        nozzle_count=count, protocol="WAYNE_DART", interface="RS485",
        status="ACTIVE", communication_status="UNKNOWN", installation_date=utcnow(),
    )
    db.add(dispenser)
    db.flush()

    nozzles, fcc_devices, fcc_uids, pos_ids = [], [], [], []
    for number in range(1, count + 1):
        nozzle = Nozzle(
            id=str(uuid.uuid4()), dispenser_id=dispenser.id,
            code=_code(db, Nozzle, Nozzle.code, "NZ"),
            number=number, name=f"Nozzle {number}", price=price, status="ACTIVE",
        )
        db.add(nozzle)
        db.flush()
        nozzles.append(nozzle)

        fcc_uid = _code(db, FCCDevice, FCCDevice.device_uid, "FCC")
        fcc = FCCDevice(
            id=str(uuid.uuid4()), device_uid=fcc_uid,
            name=f"Controller {nozzle.code}", station_id=station.id,
            dispenser_id=dispenser.id, nozzle_id=nozzle.id,
            firmware_version="ve360-fcc-bench-1.1", connection_mode="WIFI",
            calibration_factor=float(payload.get("pulses_per_litre") or 100),
            status="ACTIVE", is_online=False,
        )
        db.add(fcc)
        fcc_devices.append(fcc)
        fcc_uids.append(fcc_uid)

        terminal_id = _code(db, POSTerminal, POSTerminal.terminal_id, "POS")
        pos = POSTerminal(
            id=str(uuid.uuid4()), terminal_id=terminal_id,
            serial_number=f"SN-{uuid.uuid4().hex[:8].upper()}",
            provider="OPAY", station_id=station.id, nozzle_id=nozzle.id, is_active=True,
        )
        db.add(pos)
        db.flush()
        fcc.pos_terminal_id = pos.id
        pos_ids.append(terminal_id)

    db.flush()
    write_audit(
        db, admin, "GENERATE_HARDWARE_IDS", "Station", station.id,
        after={"station": station.code, "dispenser": dispenser.code,
               "nozzles": [n.code for n in nozzles]}, request=request,
    )
    db.commit()

    nozzle_out = [
        {
            "id": n.id, "code": n.code, "number": n.number, "price": n.price,
            "station_id": station.id, "station_code": station.code,
            "dispenser_id": dispenser.id, "dispenser_code": dispenser.code,
            "fcc_uid": fcc_uids[i], "pos_terminal_id": pos_ids[i],
        }
        for i, n in enumerate(nozzles)
    ]
    return {
        "station": {"id": station.id, "code": station.code, "name": station.name},
        "dispenser": {"id": dispenser.id, "code": dispenser.code, "name": dispenser.name},
        "nozzles": nozzle_out,
        "sketches": {
            "board01": _board01_block(station, dispenser, nozzles, fcc_uids, pos_ids, payload),
            "board03": _board03_block(station, dispenser, nozzles, fcc_uids, payload),
            "board05": _board05_block(station, nozzles, payload),
        },
        "message": "Short IDs generated. Copy a code or paste the sketch block; no manual ID typing needed.",
    }


@router.get("/records")
def records(
    db: Session = Depends(get_db),
    _: User = Depends(require_super_admin),
):
    """List generated hardware so any ID can be copied later."""
    stations = db.scalars(select(Station).order_by(Station.registered_at.desc())).all()
    out = []
    for station in stations:
        dispensers = db.scalars(
            select(Dispenser).where(Dispenser.station_id == station.id).order_by(Dispenser.code)
        ).all()
        pumps = []
        for dispenser in dispensers:
            nozzles = db.scalars(
                select(Nozzle).where(Nozzle.dispenser_id == dispenser.id).order_by(Nozzle.number)
            ).all()
            pumps.append({
                "id": dispenser.id, "code": dispenser.code, "name": dispenser.name,
                "nozzles": [{
                    "id": n.id, "code": n.code, "number": n.number, "price": n.price,
                    "fcc_uid": n.fcc.device_uid if n.fcc else None,
                    "pos_terminal_id": n.pos.terminal_id if n.pos else None,
                } for n in nozzles],
            })
        out.append({"id": station.id, "code": station.code, "name": station.name,
                    "dispensers": pumps})
    return {"stations": out}
